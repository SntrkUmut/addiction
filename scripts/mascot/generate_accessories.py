#!/usr/bin/env python3
"""Build the small runtime accessory module from the design-source JSON.

The app must not import accessories.source.json (preview, notes, @1x maps).
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = Path(__file__).resolve().parent / "accessories.source.json"
OUTPUT = ROOT / "src" / "ui" / "mascotAccessories.ts"


def round_num(value: float) -> float:
    if abs(value - round(value)) < 1e-12:
        return float(round(value))
    return float(round(value, 4))


def round_pair(values) -> list[float]:
    return [round_num(v) for v in values]


def pose_file(slug: str, pose: dict) -> str:
    files = pose.get("files") or {}
    name = files.get("")
    if name:
        return name
    return f"{slug}.png"


def main() -> None:
    source = json.loads(SOURCE.read_text())
    runtime: dict = {}
    for slug, item in source.items():
        if slug.startswith("_") or not isinstance(item, dict):
            continue
        poses = {}
        for pose_name, pose in item.get("poses", {}).items():
            entry = {
                "file": pose_file(slug, pose),
                "bbox": round_pair(pose.get("bbox") or item["bbox"]),
                "fit": {
                    "scale": round_num(pose.get("scale", 1)),
                    "rotate": round_num(pose.get("rotate", 0)),
                    "tx": round_num(pose.get("tx", 0)),
                    "ty": round_num(pose.get("ty", 0)),
                },
            }
            poses[pose_name] = entry
        region = item.get("region") or {"x": 0, "y": 0, "size": 1}
        keep_region = any(round_num(region.get(k, 0)) != (1 if k == "size" else 0) for k in ("x", "y", "size"))
        runtime[slug] = {
            "id": item["id"],
            "layer": item["layer"],
            "perPoseFiles": bool(item.get("per_pose_files")),
            "bbox": round_pair(item["bbox"]),
            "anchor": item["anchor"],
            "poses": poses,
        }
        if keep_region:
            runtime[slug]["region"] = {
                "x": round_num(region["x"]),
                "y": round_num(region["y"]),
                "size": round_num(region["size"]),
            }

    payload = json.dumps(runtime, ensure_ascii=False, indent=2)
    output = f"""/**
 * Runtime mascot accessory data.
 * Generated by scripts/mascot/generate_accessories.py — do not edit by hand.
 */
export type AccessoryFit = {{
  scale: number;
  rotate: number;
  tx: number;
  ty: number;
}};

export type AccessoryPoseData = {{
  file: string;
  bbox: readonly [number, number, number, number];
  fit: AccessoryFit;
}};

export type AccessoryRuntime = {{
  id: string;
  layer: 'front' | 'back';
  perPoseFiles: boolean;
  bbox: readonly [number, number, number, number];
  anchor: readonly [number, number] | {{ left: readonly [number, number]; right: readonly [number, number] }};
  region?: {{ x: number; y: number; size: number }};
  poses: Record<string, AccessoryPoseData>;
}};

export const MASCOT_ACCESSORIES: Record<string, AccessoryRuntime> = {payload};

export function accessoryPose(id: string, pose: string): AccessoryPoseData | null {{
  return MASCOT_ACCESSORIES[id]?.poses[pose] ?? null;
}}
"""
    OUTPUT.write_text(output)
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({OUTPUT.stat().st_size} bytes, {len(runtime)} accessories)")


if __name__ == "__main__":
    main()
